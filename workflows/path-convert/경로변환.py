# 맥 나스 경로의 접두어를 윈도우 접두어로 바꾼다. 접두어는 설정 값만 쓴다.

from config.불러오기 import 깊게, 작업경로


def 바꾸기(설정, 맥경로):
    맥접두 = 깊게(설정, "나스", "맥연결경로")
    윈접두 = 깊게(설정, "나스", "윈도우연결경로")
    편집 = 작업경로(설정, "영상편집구조")
    편집표시 = "아직 없음" if not 편집 else "경로 있음"
    원문 = (맥경로 or "").strip()
    if not 윈접두:
        return {
            "바뀐경로": "",
            "이유": "윈도우 연결 경로가 아직 없어 바꾸지 않습니다",
            "편집구조": 편집표시,
        }
    if not 맥접두:
        return {
            "바뀐경로": "",
            "이유": "맥 연결 경로가 아직 없어 바꾸지 않습니다",
            "편집구조": 편집표시,
        }
    if not 원문:
        return {
            "바뀐경로": "",
            "이유": "바꿀 경로가 비어 있습니다",
            "편집구조": 편집표시,
        }
    if not 원문.startswith(맥접두):
        return {
            "바뀐경로": "",
            "이유": "맥 연결 경로로 시작하지 않아 바꾸지 않습니다",
            "편집구조": 편집표시,
        }
    나머지 = 원문[len(맥접두):].replace("/", "\\").lstrip("\\")
    앞 = 윈접두.rstrip("\\/")
    return {
        "바뀐경로": 앞 + "\\" + 나머지 if 나머지 else 앞,
        "이유": "",
        "편집구조": 편집표시,
    }
